-- ── INSCRIPCION ───────────────────────────────────────────────
CREATE TABLE inscripcion (
    id_inscripcion INT UNSIGNED NOT NULL AUTO_INCREMENT,
    matricula BIGINT UNSIGNED NOT NULL,
    id_grupo INT UNSIGNED NOT NULL,
    fecha_inscripcion DATE NOT NULL,
    estatus ENUM('Activa','Baja') NOT NULL DEFAULT 'Activa',
    calificacion DECIMAL(4,2) DEFAULT NULL,
    PRIMARY KEY (id_inscripcion),
    UNIQUE KEY uq_ai (matricula,id_grupo),
    FOREIGN KEY (matricula) REFERENCES alumno(matricula) ON UPDATE CASCADE,
    FOREIGN KEY (id_grupo) REFERENCES grupo(id_grupo) ON UPDATE CASCADE
) ENGINE=InnoDB;

DELIMITER $$
CREATE TRIGGER trg_check_cupo BEFORE INSERT ON inscripcion
FOR EACH ROW BEGIN
    DECLARE v INT;
    SELECT cupo_disponible INTO v FROM grupo WHERE id_grupo=NEW.id_grupo;
    IF v<=0 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Sin cupo disponible.'; END IF;
END$$
CREATE TRIGGER trg_check_dup BEFORE INSERT ON inscripcion
FOR EACH ROW BEGIN
    DECLARE v INT;
    SELECT COUNT(*) INTO v FROM inscripcion i
    JOIN grupo g1 ON i.id_grupo=g1.id_grupo
    JOIN grupo g2 ON NEW.id_grupo=g2.id_grupo
    WHERE i.matricula=NEW.matricula AND g1.clave_materia=g2.clave_materia AND i.estatus='Activa';
    IF v>0 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Ya inscrito en esta materia.'; END IF;
END$$
CREATE TRIGGER trg_reduce_cupo AFTER INSERT ON inscripcion
FOR EACH ROW BEGIN
    UPDATE grupo SET cupo_disponible=cupo_disponible-1 WHERE id_grupo=NEW.id_grupo AND cupo_disponible>0;
END$$
CREATE TRIGGER trg_restaurar_cupo AFTER UPDATE ON inscripcion
FOR EACH ROW BEGIN
    IF NEW.estatus='Baja' AND OLD.estatus='Activa' THEN
        UPDATE grupo SET cupo_disponible=cupo_disponible+1 WHERE id_grupo=NEW.id_grupo AND cupo_disponible<cupo_maximo;
    END IF;
END$$
CREATE TRIGGER trg_max_opt BEFORE INSERT ON inscripcion
FOR EACH ROW BEGIN
    DECLARE v INT;
    SELECT COUNT(*) INTO v FROM inscripcion i JOIN grupo g ON i.id_grupo=g.id_grupo
    JOIN materia m ON g.clave_materia=m.clave_materia
    WHERE i.matricula=NEW.matricula AND m.tipo='Optativa' AND i.estatus='Activa';
    IF v>=3 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Límite de 3 optativas alcanzado.'; END IF;
END$$
DELIMITER ;
